"""M13: build the LaTeX report folder (latex/) from report/report.md + results.
No numbers are typed here: the body is converted from the generated report.md."""
import re, shutil, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "latex"

PREAMBLE = r"""\documentclass[11pt]{article}
\usepackage[margin=1in]{geometry}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usepackage{microtype}
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{longtable}
\usepackage{array}
\usepackage{float}
\usepackage{amsmath}
\usepackage[hidelinks]{hyperref}
\usepackage{xcolor}
\usepackage{caption}
\captionsetup{font=small}
\usepackage{etoolbox}
\AtBeginEnvironment{longtable}{\footnotesize}
\setlength{\emergencystretch}{3em}
\providecommand{\tightlist}{\setlength{\itemsep}{0pt}\setlength{\parskip}{0pt}}
\providecommand{\pandocbounded}[1]{#1}
\setkeys{Gin}{width=\linewidth,height=0.38\textheight,keepaspectratio}
\title{The Cost of Interpretability in Speech Emotion Recognition on IEMOCAP}
\author{Initial full-length report (to be trimmed)}
\date{\today}
\begin{document}
\maketitle
\tableofcontents
\clearpage
"""
END = "\n\\end{document}\n"

def pandoc(md: str) -> str:
    r = subprocess.run(["pandoc", "-f", "markdown+implicit_figures+pipe_tables", "-t", "latex",
                        "--top-level-division=section", "--shift-heading-level-by=-1", "--wrap=preserve"],
                       input=md, capture_output=True, text=True, check=True)
    return r.stdout

SHORT_DROP = ("### 4.2", "### 4.4", "## 5.")   # sections dropped from the short version

def drop_sections(md):
    parts = re.split(r"(?m)^(?=#{2,3} )", md)
    return "".join(p for p in parts if not p.startswith(SHORT_DROP))

def main(short=False):
    global OUT
    OUT = ROOT / ("latex_short" if short else "latex")
    (OUT / "figures").mkdir(parents=True, exist_ok=True)
    (OUT / "tables").mkdir(exist_ok=True)
    md = (ROOT / "report/report.md").read_text()
    md = re.sub(r"^# .*\n", "", md, count=1)                       # title handled by \maketitle
    if short:
        md = drop_sections(md)
    md = re.sub(r"^\*Generated.*\n", "", md, flags=re.M)
    figs = sorted(set(re.findall(r"\(\.\./figures/([^)]+)\)", md)))
    for f in figs:
        shutil.copy(ROOT / "figures" / f, OUT / "figures" / f)
    for t in (ROOT / "report/tables").glob("*.csv"):
        shutil.copy(t, OUT / "tables" / t.name)
    # figures -> numbered figure environments with captions from alt text
    md = re.sub(r"!\[([^\]]*)\]\(\.\./figures/([^)]+)\)", r"![\1](figures/\2)", md)
    md = re.sub(r"(?m)^(#{2,3}) \d+(\.\d+)?\.? ", r"\1 ", md)   # LaTeX numbers sections itself
    body = pandoc(md)
    # pandoc emits \pandocbounded{\includegraphics..} and figure envs; force [H]
    body = re.sub(r",alt=\{[^}]*\}", "", body)
    body = body.replace(r"\begin{figure}", r"\begin{figure}[H]")
    body = body.replace(r"\begin{figure}[H][H]", r"\begin{figure}[H]")
    # appendix: interpretability narrative
    story = None if short else ROOT / "results/m11/feature_story.md"
    app = "\n\\clearpage\n\\appendix\n" + ("" if short else "\\section{Interpretable model: full feature story}\n")
    if story and story.exists():
        s = re.sub(r"^# .*\n", "", story.read_text(), count=1)
        app += pandoc(s)
    extra = {"m4_agreement_by_class.png": "Rater agreement (Krippendorff alpha) by class.",
             "m7_confusions.png": "Confusion matrices of the four headline models.",
             "m10_impro_vs_script.png": "Improvised versus scripted dialogs.",
             "m11_tree.png": "The budgeted decision tree (eGeMAPS)."}
    app += "\n\\section{Additional figures}\n" if not short else ""
    for f, cap in ({} if short else extra).items():
        if (ROOT / "figures" / f).exists():
            shutil.copy(ROOT / "figures" / f, OUT / "figures" / f)
            app += "\\begin{figure}[H]\\centering\\includegraphics{figures/%s}\\caption{%s}\\end{figure}\n" % (f, cap)
    app += "\n\\section{Reproducibility}\n" + pandoc(
        "Every number in this document is generated by `src/m12_report.py` from files under `results/`; "
        "the LaTeX body is converted from `report/report.md` by `src/m13_latex.py`. "
        "Fixed seeds are 1337, 2024 and 7. The CSV tables behind Tables 1--10 are in `tables/`. "
        "Verification output: `results/m12/verification.json`. "
        "Rebuild with `python src/m12_report.py && python src/m13_latex.py`.")
    (OUT / "main.tex").write_text(PREAMBLE + body + app + END)
    (OUT / "README.md").write_text("Build: `pdflatex main.tex` (twice for the table of contents). "
        "Figures in `figures/`, source CSV tables in `tables/`. Regenerate with `python src/m13_latex.py`.\n")
    print("figures:", len(figs), "->", OUT)

if __name__ == "__main__":
    import sys
    main(short="--short" in sys.argv)
